$basePath = __DIR__ . '/lang';

foreach($keys as $group => $groupedKeys) {
    foreach($langs as $lang) {
        $filePath = "$basePath/$lang/$group.php";
        
        // If file doesn't exist, create it
        if (!file_exists($filePath)) {
            file_put_contents($filePath, "<?php\n\nreturn [\n];\n");
        }
        
        $content = file_get_contents($filePath);
        $addedCount = 0;
        
        // Strip out the last ]; and append
        $pos = strrpos($content, ']');
        if ($pos !== false) {
            $prependStr = "";
            foreach($groupedKeys as $key => $values) {
                // Check if key already exists (simple string check to prevent duplicates)
                if (strpos($content, "'$key'") === false && strpos($content, "\"$key\"") === false) {
                    $val = str_replace("'", "\\'", $values[$lang]);
                    $prependStr .= "    '$key' => '$val',\n";
                    $addedCount++;
                }
            }
            if ($prependStr !== "") {
                $content = substr_replace($content, $prependStr . "]", $pos, 1);
                file_put_contents($filePath, $content);
            }
        }
        echo "Group $group ($lang): Added $addedCount keys\n";
    }
}
